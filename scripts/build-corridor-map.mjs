/**
 * Pre-computes the dotted UAE → India corridor map used by
 * src/components/motion-library/inspira-ui/WorldMap.tsx.
 *
 * Inspira UI's WorldMap builds its dots at runtime with `dotted-map`, which
 * ships the full world GeoJSON to the browser. Pre-computing keeps the same
 * look while shipping only ~10 KB of coordinates.
 *
 *   node scripts/build-corridor-map.mjs
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import DottedMap from "dotted-map";

const REGION = { lat: { min: 6, max: 37 }, lng: { min: 33, max: 94 } };
const PLACES = {
  dubai: { lat: 25.2048, lng: 55.2708, label: "Dubai" },
  delhi: { lat: 28.6139, lng: 77.209, label: "New Delhi" },
};

const map = new DottedMap({ height: 40, grid: "diagonal", region: REGION });
const pins = Object.fromEntries(
  Object.entries(PLACES).map(([key, place]) => {
    const pin = map.addPin({ lat: place.lat, lng: place.lng, data: key });
    return [key, { x: +pin.x.toFixed(2), y: +pin.y.toFixed(2), label: place.label }];
  }),
);
const points = map
  .getPoints()
  .filter((point) => !point.data)
  .map((point) => [+point.x.toFixed(2), +point.y.toFixed(2)]);

const file = `/* Generated by scripts/build-corridor-map.mjs — do not edit by hand. */
export const CORRIDOR_MAP = {
  width: ${map.image.width},
  height: ${map.image.height},
  pins: ${JSON.stringify(pins)},
  points: ${JSON.stringify(points.flat())},
} as const;
`;
const out = fileURLToPath(
  new URL("../src/components/motion-library/inspira-ui/corridorMapData.ts", import.meta.url),
);
writeFileSync(out, file);
console.log(`corridor map: ${points.length} dots, ${map.image.width}×${map.image.height}`, pins);
